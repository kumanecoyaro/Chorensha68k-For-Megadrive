#!/usr/bin/env python3
"""Convert Chorensha68k X68000 ADPCM sound effects into Mega Drive DAC samples.

usage: convert_pcm.py SZ2_PCM.CNF PCM_DAT_DIR OUT_DIR [--wav DIR]

X68000: OKI MSM6258 4-bit ADPCM, low nibble first.  Every entry of SZ2_PCM.CNF
uses STAT=$403 (IOCS _ADPCMOUT: rate 4 = 15.625 kHz, both channels).
Most entries use STAT=$403 (rate 4 = 15.625 kHz); a few replay the same file
with STAT=$303 (10.416 kHz) for a lower pitch.
Mega Drive: 8-bit unsigned PCM written by the Z80 to YM2612 register $2A at a
fixed 15.625 kHz; lower-rate entries are stored pre-stretched (linear
interpolation) as separate samples.

Output:
  OUT_DIR/pcm.bin    all samples, each starting on an even address
  OUT_DIR/pcm.c/.h   pcm_table[256] = { offset, length, priority } by PCM number
"""
import os, re, struct, sys, wave

STEPS = [16, 17, 19, 21, 23, 25, 28, 31, 34, 37, 41, 45, 50, 55, 60, 66, 73, 80, 88, 97,
         107, 118, 130, 143, 157, 173, 190, 209, 230, 253, 279, 307, 337, 371, 408, 449,
         494, 544, 598, 658, 724, 796, 876, 963, 1060, 1166, 1282, 1411, 1552]
INDEX_ADJ = [-1, -1, -1, -1, 2, 4, 6, 8]
RATES = {0: 3906, 1: 5208, 2: 7812, 3: 10416, 4: 15625}

def adpcm_decode(data):
    """MSM6258 ADPCM -> list of 12-bit signed samples."""
    sig, idx, out = 0, 0, []
    for b in data:
        for n in (b & 15, b >> 4):
            step = STEPS[idx]
            d = step >> 3
            if n & 1: d += step >> 2
            if n & 2: d += step >> 1
            if n & 4: d += step
            sig = sig - d if n & 8 else sig + d
            sig = max(-2048, min(2047, sig))
            idx = max(0, min(48, idx + INDEX_ADJ[n & 7]))
            out.append(sig)
    return out

def resample(samples, src, dst):
    """Linear interpolation from src Hz to dst Hz (stretches when src < dst)."""
    if src == dst:
        return samples
    n = len(samples) * dst // src
    out = []
    for i in range(n):
        p = i * src / dst
        k = int(p); f = p - k
        a = samples[k]; b = samples[min(k + 1, len(samples) - 1)]
        out.append(int(round(a + (b - a) * f)))
    return out

def to_u8(samples):
    return bytes(max(0, min(255, (s >> 4) + 128)) for s in samples)

def parse_cnf(path):
    text = open(path, 'rb').read().decode('cp932')
    ents = []
    for m in re.finditer(r'^\s*PCM_No\.\$([0-9A-Fa-f]+)\s*:\s*FILE=\s*(\S+)\s*,\s*STAT=\$([0-9A-Fa-f]+)\s*,\s*PR=\$([0-9A-Fa-f]+)',
                         text, re.M):
        ents.append((int(m.group(1), 16), m.group(2), int(m.group(3), 16), int(m.group(4), 16)))
    return ents

def main(cnf, pcmdir, out, wavdir=None):
    os.makedirs(out, exist_ok=True)
    ents = parse_cnf(cnf)
    blob = bytearray(); files = {}
    table = [(0, 0, 0)] * 256
    for no, fname, stat, pr in ents:
        rate = RATES[(stat >> 8) & 7]
        key = (fname, rate)
        if key not in files:
            raw = open(os.path.join(pcmdir, os.path.basename(fname)), 'rb').read()
            pcm = to_u8(resample(adpcm_decode(raw), rate, 15625))
            files[key] = (len(blob), len(pcm))
            blob += pcm
            if len(blob) & 1:
                blob.append(0x80)
            if wavdir:
                os.makedirs(wavdir, exist_ok=True)
                w = wave.open(os.path.join(wavdir, f'{os.path.basename(fname)}_{rate}.wav'), 'wb')
                w.setnchannels(1); w.setsampwidth(1); w.setframerate(15625); w.writeframes(pcm); w.close()
        off, ln = files[key]
        table[no] = (off, ln, pr)
    open(os.path.join(out, 'pcm.bin'), 'wb').write(blob)
    c = ['/* generated by tools/convert_pcm.py - do not edit */', '#include "pcm.h"', '',
         'const PcmEntry pcm_table[256] = {']
    for no, (off, ln, pr) in enumerate(table):
        if ln:
            c.append(f'  [0x{no:02X}] = {{ 0x{off:06X}, {ln}, 0x{pr:02X} }},')
    c.append('};')
    open(os.path.join(out, 'pcm.c'), 'w').write('\n'.join(c) + '\n')
    open(os.path.join(out, 'pcm.h'), 'w').write('\n'.join([
        '/* generated by tools/convert_pcm.py - do not edit */',
        '#ifndef PCM_H', '#define PCM_H', '#include "types.h"',
        'typedef struct { u32 offset; u32 length; u16 priority; } PcmEntry;',
        'extern const PcmEntry pcm_table[256];',
        'extern const u8 pcm_data[];            /* pcm.bin, 32 KB aligned (pcm_data.s) */',
        f'#define PCM_RATE 15625', f'#define PCM_DATA_SIZE {len(blob)}', '#endif', '']))
    print(f'{len(ents)} entries, {len(files)} files, {len(blob)} bytes of 8-bit PCM')

if __name__ == '__main__':
    a = sys.argv[1:]
    wav = None
    if '--wav' in a:
        i = a.index('--wav'); wav = a[i + 1]; del a[i:i + 2]
    main(*a, wavdir=wav)
